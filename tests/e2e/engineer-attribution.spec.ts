import { expect, test } from "@playwright/test";
import { authenticatedContext, identityHeaders, skipTourIfOpen } from "./fixtures";
import type { FloorSnapshot } from "@/lib/floor-types";

test("legacy engineers verify before code execution and retain credit across History and Review", async ({ browser }) => {
  test.setTimeout(120_000);
  const owner = await authenticatedContext(browser, "attribution-owner", "attribution-owner@example.com", "Dispatch", "Owner");
  expect((await owner.request.put("/api/account/credentials/openai", { data: { apiKey: "sk-openai-e2e-accepted" } })).ok()).toBe(true);
  const engineer = await browser.newContext({ extraHTTPHeaders: identityHeaders("legacy-attribution-e2e", "legacy-attribution@example.com", "Legacy Engineer") });
  const repositories = await (await owner.request.get("/api/account/github/repositories")).json();
  const repository = repositories.repositories[0];
  const response = await owner.request.post("/api/sessions", { data: { title: "Engineer attribution", repositoryId: repository.id, accountInstallationId: repository.accountInstallationId } });
  expect(response.status()).toBe(201);
  const { session, inviteUrl } = await response.json();
  const root = `/api/sessions/${session.id}`;
  await owner.request.patch(`${root}/routing`, { data: { autoDispatch: false, autoProvisionAgents: false } });
  const engineerPage = await engineer.newPage();
  await engineerPage.goto(new URL(inviteUrl).pathname);
  await engineerPage.getByRole("button", { name: "Join session" }).click();
  await engineerPage.goto(`/session/${session.id}/floor`);
  await skipTourIfOpen(engineerPage);
  const firstAgent = await (await owner.request.post(`${root}/agents`, { data: { usageScope: "session", name: "First builder", role: "Engineer", task: "Implement features" } })).json();
  const firstId = firstAgent.floor.agents[0].id;
  const secondAgent = await (await owner.request.post(`${root}/agents`, { data: { usageScope: "session", name: "Second builder", role: "Engineer", task: "Implement features" } })).json();
  const secondId = secondAgent.floor.agents.find((a: { name: string }) => a.name === "Second builder").id;
  const queued = await (await engineer.request.post(`${root}/queue`, { data: { prompt: "Add engineer attribution feature", agentId: firstId } })).json();
  const waitingId = queued.floor.queue[0].id;
  const denied = await owner.request.post(`${root}/queue/${waitingId}/run`);
  expect(denied.status()).toBe(409);
  expect((await denied.json()).code).toBe("github_verification_required");
  await engineerPage.reload();
  await expect(engineerPage.getByText(/Waiting for GitHub verification: Legacy E\./)).toBeVisible();
  await owner.request.post(`${root}/queue`, { data: { prompt: "Add second published independent feature", agentId: secondId } });
  await owner.request.patch(`${root}/routing`, { data: { autoDispatch: true } });
  const floor = async (): Promise<FloorSnapshot> => (await (await owner.request.get(`${root}/floor`)).json()).floor;
  await expect.poll(async () => (await floor()).runs.some((run) => run.agentId === secondId && run.status === "integrated")).toBe(true);
  expect((await floor()).queue.find((item) => item.id === waitingId)?.status).toBe("queued");
  await engineerPage.goto("/home/settings?section=connections");
  await expect(engineerPage.getByText("Verify your GitHub account before code prompts can run.")).toBeVisible();
  await engineerPage.getByRole("button", { name: "Add GitHub access" }).click();
  await expect(engineerPage.getByText("GitHub credit:")).toBeVisible();
  await expect.poll(async () => (await floor()).runs.find((run) => run.queueItemId === waitingId)?.status).toBe("integrated");
  const run = (await floor()).runs.find((run) => run.queueItemId === waitingId)!;
  expect(run.attribution?.authors).toEqual([{ userId: "12345678-1234-4234-8234-123456789abc", githubId: "78187493394", login: "test-12345678" }]);
  expect(run.createdBy).not.toBe(run.attribution?.authors[0].userId);
  await engineerPage.goto(`/session/${session.id}/floor`);
  await skipTourIfOpen(engineerPage);
  await engineerPage.getByRole("button", { name: "Run history", exact: true }).click();
  const history = engineerPage.getByRole("dialog", { name: "Run history" });
  await expect(history.getByText(/Prompted by Legacy E\./)).toBeVisible();
  await expect(history.getByRole("link", { name: "@test-12345678" })).toHaveAttribute("href", "https://github.com/test-12345678");
  await expect(history.getByRole("link", { name: "View commit on GitHub" }).first()).toHaveAttribute("href", /github\.com\/openfloor-test\/repository-integration\/commit\/[0-9a-f]{40}$/);
  await history.getByRole("button", { name: "Close", exact: true }).click();
  await engineerPage.getByRole("button", { name: "Review", exact: true }).click();
  await engineerPage.getByRole("button", { name: "Prompts", exact: true }).click();
  await expect(engineerPage.getByRole("link", { name: "@test-12345678" })).toBeVisible();
  await engineerPage.reload();
  expect((await floor()).runs.find((item) => item.id === run.id)?.attribution).toEqual(run.attribution);
  await owner.close();
  await engineer.close();
});
